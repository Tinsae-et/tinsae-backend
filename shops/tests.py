class PublicShopProductsApiTest(TestCase):
    """The anonymous catalogue nested under /api/v1/shop/<slug>/products/."""

    def setUp(self):
        self.owner = User.objects.create_user(username="merchant", password="pass")
        self.other_owner = User.objects.create_user(
            username="other_merchant", password="pass"
        )
        self.shop = Shop.objects.create(name="Owner Shop", owner=self.owner)
        self.other_shop = Shop.objects.create(name="Other Shop", owner=self.other_owner)
        self.category = Category.objects.create(name="Phones", slug="phones")
        self.accessory_category = Category.objects.create(
            name="Accessories", slug="accessories"
        )
        now = timezone.now()

        # Product 1: fresh (confirmed now)
        self.fresh_product = Product.objects.create(
            shop=self.shop,
            category=self.category,
            brand="Samsung",
            name="Galaxy A15",
            price="12500.00",
            last_confirmed_at=now,
            is_available=True,
        )
        # Product 2: unavailable (paused/sold out) -> should be excluded
        self.unavailable_product = Product.objects.create(
            shop=self.shop,
            category=self.category,
            brand="Nokia",
            name="Nokia 110",
            price="1300.00",
            last_confirmed_at=now,
            is_available=False,
        )
        # Product 3: confirmed 3 days ago (aging/almost expired) -> should be included
        self.aging_product = Product.objects.create(
            shop=self.shop,
            category=self.accessory_category,
            brand="Apple",
            name="AirPods Pro",
            price="33000.00",
            last_confirmed_at=now - timedelta(days=3),
            is_available=True,
        )
        # Product 4: unconfirmed (last_confirmed_at is NULL) -> should be included
        self.unconfirmed_product = Product.objects.create(
            shop=self.shop,
            category=self.accessory_category,
            brand="Anker",
            name="Fast Charger",
            price="1500.00",
            last_confirmed_at=None,
            is_available=True,
        )
        # Product on another shop -> should be excluded
        self.other_shop_product = Product.objects.create(
            shop=self.other_shop,
            category=self.category,
            brand="Apple",
            name="iPhone 15",
            price="45000.00",
            last_confirmed_at=now,
            is_available=True,
        )

    def _url(self, shop_slug=None):
        return f"/api/v1/shop/{shop_slug or self.shop.slug}/products/"

    def test_anonymous_request_lists_all_available_products_including_unconfirmed_in_post_order(
        self,
    ):
        response = APIClient().get(self._url())

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["count"], 3)
        # Default order is post order (-created_at): newest first
        expected_slugs = [
            self.unconfirmed_product.slug,
            self.aging_product.slug,
            self.fresh_product.slug,
        ]
        returned_slugs = [r["slug"] for r in response.data["results"]]
        self.assertEqual(returned_slugs, expected_slugs)

    def test_unknown_shop_returns_404(self):
        response = APIClient().get(self._url("missing-shop"))

        self.assertEqual(response.status_code, 404)

    def test_category_filter_limits_results(self):
        response = APIClient().get(
            self._url(), {"category": self.accessory_category.slug}
        )

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["count"], 2)
        returned_slugs = {r["slug"] for r in response.data["results"]}
        self.assertEqual(
            returned_slugs, {self.aging_product.slug, self.unconfirmed_product.slug}
        )

    def test_ordering_query_param_sorts_results(self):
        response = APIClient().get(self._url(), {"ordering": "price"})

        self.assertEqual(response.status_code, 200)
        prices = [r["price"] for r in response.data["results"]]
        self.assertEqual(prices, ["1500.00", "12500.00", "33000.00"])

    def test_search_query_filters_results(self):
        response = APIClient().get(self._url(), {"q": "Galaxy"})

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["count"], 1)
        self.assertEqual(response.data["results"][0]["slug"], self.fresh_product.slug)

    def test_invalid_ordering_field_returns_400(self):
        response = APIClient().get(self._url(), {"ordering": "not_a_field"})

        self.assertEqual(response.status_code, 400)
        self.assertIn("ordering", response.data)


class ShopProductApiTest(TestCase):
    """The merchant-facing CRUD nested under /api/v1/shops/<slug>/products/."""

    def setUp(self):
        self.owner = User.objects.create_user(username="merchant", password="pass")
        self.other_owner = User.objects.create_user(
            username="other_merchant", password="pass"
        )
        self.shop = Shop.objects.create(name="Owner Shop", owner=self.owner)
        self.other_shop = Shop.objects.create(name="Other Shop", owner=self.other_owner)
        self.category = Category.objects.create(name="Phones", slug="phones")
        self.product = Product.objects.create(
            shop=self.shop,
            category=self.category,
            brand="Samsung",
            name="Galaxy A15",
            price="12500.00",
        )
        self.client = APIClient()

    def _url(self, shop=None, slug=None):
        shop = shop or self.shop
        tail = f"{slug}/" if slug else ""
        return f"/api/v1/shops/{shop.slug}/products/{tail}"

    # --- happy path -----------------------------------------------------

    def test_owner_can_create_product(self):
        self.client.force_authenticate(self.owner)

        response = self.client.post(
            self._url(),
            {
                "brand": "Anker",
                "name": "PowerPort",
                "description": "Fast charger",
                "price": "450.00",
                "currency": "ETB",
                "category": self.category.slug,
                "specs": {"ports": 2},
            },
            format="json",
        )

        self.assertEqual(response.status_code, 201)
        created = Product.objects.get(slug=response.data["slug"])
        self.assertEqual(created.shop, self.shop)
        self.assertEqual(created.category, self.category)
        self.assertEqual(created.brand, "Anker")

    def test_new_product_opens_fresh(self):
        # The AC that a bare `confirmation_status="fresh"` only appeared to meet:
        # the column already defaults to "fresh", so the timestamp is the part
        # that actually has to be written.
        self.client.force_authenticate(self.owner)

        response = self.client.post(
            self._url(),
            {
                "brand": "Anker",
                "name": "PowerPort",
                "price": "450.00",
                "category": self.category.slug,
            },
            format="json",
        )

        self.assertEqual(response.status_code, 201)
        created = Product.objects.get(slug=response.data["slug"])
        self.assertIsNotNone(created.last_confirmed_at)
        self.assertEqual(created.confirmation_status, ConfirmationStatus.FRESH)
        self.assertEqual(created.freshness, Freshness.FRESH)

    def test_owner_can_edit_product(self):
        self.client.force_authenticate(self.owner)

        response = self.client.patch(
            self._url(slug=self.product.slug),
            {"name": "Galaxy A15 5G", "price": "13500.00"},
            format="json",
        )

        self.assertEqual(response.status_code, 200)
        self.product.refresh_from_db()
        self.assertEqual(self.product.name, "Galaxy A15 5G")
        self.assertEqual(self.product.price, Decimal("13500.00"))

    def test_owner_can_delete_product(self):
        self.client.force_authenticate(self.owner)

        response = self.client.delete(self._url(slug=self.product.slug))

        self.assertEqual(response.status_code, 204)
        self.assertFalse(Product.objects.filter(pk=self.product.pk).exists())

    def test_owner_can_toggle_availability(self):
        self.client.force_authenticate(self.owner)

        response = self.client.patch(
            self._url(slug=self.product.slug),
            {"is_available": False},
            format="json",
        )

        self.assertEqual(response.status_code, 200)
        self.product.refresh_from_db()
        self.assertFalse(self.product.is_available)

    # --- scoping and ownership ------------------------------------------

    def test_list_is_scoped_to_the_shop_in_the_url(self):
        Product.objects.create(
            shop=self.other_shop,
            category=self.category,
            brand="Nokia",
            name="Not Mine",
            price="900.00",
        )
        self.client.force_authenticate(self.owner)

        response = self.client.get(self._url())

        self.assertEqual(response.status_code, 200)
        names = [row["name"] for row in response.data["results"]]
        self.assertEqual(names, ["Galaxy A15"])

    def test_other_shop_owner_cannot_edit_product(self):
        # 404 rather than 403: the queryset is scoped by owner, so someone
        # else's product is simply not there. The AC allows either.
        self.client.force_authenticate(self.other_owner)

        response = self.client.patch(
            self._url(slug=self.product.slug),
            {"name": "Unauthorized edit"},
            format="json",
        )

        self.assertEqual(response.status_code, 404)
        self.product.refresh_from_db()
        self.assertEqual(self.product.name, "Galaxy A15")

    def test_other_shop_owner_cannot_delete_product(self):
        self.client.force_authenticate(self.other_owner)

        response = self.client.delete(self._url(slug=self.product.slug))

        self.assertEqual(response.status_code, 404)
        self.assertTrue(Product.objects.filter(pk=self.product.pk).exists())

    def test_cannot_create_into_someone_elses_shop(self):
        self.client.force_authenticate(self.other_owner)

        response = self.client.post(
            self._url(shop=self.shop),
            {
                "brand": "Anker",
                "name": "Smuggled",
                "price": "450.00",
                "category": self.category.slug,
            },
            format="json",
        )

        self.assertEqual(response.status_code, 404)
        self.assertFalse(Product.objects.filter(name="Smuggled").exists())

    def test_anonymous_cannot_create(self):
        # Regression guard: with only IsOwnerOrReadOnly, DRF never calls
        # has_object_permission on create, so this reached the view body.
        response = self.client.post(
            self._url(),
            {
                "brand": "Anker",
                "name": "PowerPort",
                "price": "450.00",
                "category": self.category.slug,
            },
            format="json",
        )

        self.assertEqual(response.status_code, 401)
        self.assertFalse(Product.objects.filter(name="PowerPort").exists())

    def test_anonymous_cannot_list(self):
        response = self.client.get(self._url())
        self.assertEqual(response.status_code, 401)

