from django.test import TestCase
from rest_framework.test import APIClient

from catalog.models import Category, Product
from users.models import User

from .models import Shop


class ShopModelTest(TestCase):
    def setUp(self):
        self.owner = User.objects.create_user(
            username="merchant", email="merchant@example.com", password="pass"
        )

    def test_create_and_slug_autogenerated(self):
        shop = Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        self.assertEqual(shop.slug, "abebe-grocery")
        self.assertFalse(shop.is_verified)
        self.assertIsNotNone(shop.created_at)

    def test_slug_uniqueness_for_duplicate_names(self):
        first = Shop.objects.create(name="Abebe Grocery", owner=self.owner)
        second = Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        self.assertEqual(first.slug, "abebe-grocery")
        self.assertNotEqual(first.slug, second.slug)
        self.assertEqual(second.slug, "abebe-grocery-2")


class ShopDetailExposureTest(TestCase):
    """The shop detail endpoint is readable anonymously — internal fields on it
    are readable anonymously too unless the serializer withholds them."""

    def setUp(self):
        self.owner = User.objects.create_user(
            username="shop_owner", email="owner@example.com", password="pass"
        )
        self.other = User.objects.create_user(
            username="rival", email="rival@example.com", password="pass"
        )
        self.shop = Shop.objects.create(
            name="Bole Electronics",
            owner=self.owner,
            phone="+251911100001",
            telegram_chat_id="987654321",
        )
        self.url = f"/api/v1/shops/{self.shop.slug}/"

    def test_anonymous_detail_hides_internal_fields(self):
        response = APIClient().get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data)
        self.assertNotIn("owner", response.data)
        self.assertEqual(response.data["phone"], "+251911100001")

    def test_another_merchant_cannot_read_the_chat_id(self):
        client = APIClient()
        client.force_authenticate(self.other)

        response = client.get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data)

    def test_owner_still_sees_their_own_chat_id(self):
        client = APIClient()
        client.force_authenticate(self.owner)

        response = client.get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["telegram_chat_id"], "987654321")

    def test_list_never_carried_the_chat_id(self):
        response = APIClient().get("/api/v1/shops/")

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data["results"][0])


class ManageMyProductsApiTest(TestCase):
    def setUp(self):
        self.owner = User.objects.create_user(username="merchant", password="pass")
        self.other_owner = User.objects.create_user(
            username="other_merchant", password="pass"
        )
        self.shop = Shop.objects.create(name="Owner Shop", owner=self.owner)
        Shop.objects.create(name="Other Shop", owner=self.other_owner)
        self.category = Category.objects.create(name="Phones", slug="phones")
        self.product = Product.objects.create(
            shop=self.shop,
            category=self.category,
            brand="Samsung",
            name="Galaxy A15",
            price="12500.00",
        )
        self.client = APIClient()

    def test_owner_can_create_product(self):
        self.client.force_authenticate(self.owner)

        response = self.client.post(
            "/api/v1/products/",
            {
                "brand": "Anker",
                "name": "PowerPort",
                "description": "Fast charger",
                "price": "450.00",
                "currency": "ETB",
                "category_slug": self.category.slug,
                "specs": {"ports": 2},
            },
            format="json",
        )

        self.assertEqual(response.status_code, 201)
        created = Product.objects.get(slug=response.data["slug"])
        self.assertEqual(created.shop, self.shop)
        self.assertEqual(created.category, self.category)
        self.assertEqual(created.brand, "Anker")

    def test_owner_can_edit_product(self):
        self.client.force_authenticate(self.owner)

        response = self.client.patch(
            f"/api/v1/products/{self.product.slug}/",
            {"name": "Galaxy A15 5G", "price": "13500.00"},
            format="json",
        )

        self.assertEqual(response.status_code, 200)
        self.product.refresh_from_db()
        self.assertEqual(self.product.name, "Galaxy A15 5G")
        self.assertEqual(self.product.price, float("13500.00"))

    def test_other_shop_owner_cannot_edit_product(self):
        self.client.force_authenticate(self.other_owner)

        response = self.client.patch(
            f"/api/v1/products/{self.product.slug}/",
            {"name": "Unauthorized edit"},
            format="json",
        )

        self.assertEqual(response.status_code, 403)
        self.product.refresh_from_db()
        self.assertEqual(self.product.name, "Galaxy A15")
