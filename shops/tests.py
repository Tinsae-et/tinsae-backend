class ShopModelTest(TestCase):
    def setUp(self):
        self.owner = User.objects.create_user(
            username="merchant", email="merchant@example.com", password="pass"
        )

    def test_create_and_slug_autogenerated(self):
        shop = Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        self.assertEqual(shop.slug, "abebe-grocery")
        self.assertFalse(shop.is_verified)
        self.assertIsNotNone(shop.created_at)

    def test_slug_uniqueness_for_duplicate_names(self):
        first = Shop.objects.create(name="Abebe Grocery", owner=self.owner)
        second = Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        self.assertEqual(first.slug, "abebe-grocery")
        self.assertNotEqual(first.slug, second.slug)
        self.assertEqual(second.slug, "abebe-grocery-2")

    def test_a_slug_taken_between_the_scan_and_the_insert_is_retried(self):
        """The scan is check-then-act; only the unique index arbitrates.

        Two concurrent creates of the same name both scan, both find the slug
        free, and both insert. Standing in for that race: hand the first
        attempt a slug that is already taken, which is exactly what the loser
        of it sees. This is also the only test that exercises the savepoint --
        without `atomic()` around each attempt the retry's own query would
        raise TransactionManagementError instead of retrying.
        """
        Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        with mock.patch(
            "core.slugs.available_slug",
            side_effect=["abebe-grocery", "abebe-grocery-2"],
        ) as scan:
            second = Shop.objects.create(name="Abebe Grocery", owner=self.owner)

        self.assertEqual(second.slug, "abebe-grocery-2")
        self.assertEqual(scan.call_count, 2)

    def test_amharic_only_name_slug_fallback(self):
        first = Shop.objects.create(name="ተስፋ ሞባይል", owner=self.owner)
        second = Shop.objects.create(name="ተስፋ ሞባይል", owner=self.owner)
        self.assertEqual(first.slug, "shop")
        self.assertEqual(second.slug, "shop-2")

    def test_an_unrelated_integrity_error_is_not_retried(self):
        """A violation that is not a slug collision surfaces on attempt one.

        Retrying it would reproduce the same error five times over and bury the
        real one. Here it is a NOT NULL on `name`, which has nothing to do with
        the slug.
        """
        with mock.patch("core.slugs.available_slug", wraps=available_slug) as scan:
            with self.assertRaises(IntegrityError):
                Shop.objects.create(name=None, owner=self.owner)

        self.assertEqual(scan.call_count, 1)

    def test_create_without_coordinates_defaults_to_none(self):
        shop = Shop.objects.create(name="No Location Shop", owner=self.owner)
        self.assertIsNone(shop.latitude)
        self.assertIsNone(shop.longitude)

    def test_create_with_coordinates(self):
        shop = Shop.objects.create(
            name="Located Shop",
            owner=self.owner,
            latitude=Decimal("9.024970"),
            longitude=Decimal("38.746890"),
        )
        self.assertEqual(shop.latitude, Decimal("9.024970"))
        self.assertEqual(shop.longitude, Decimal("38.746890"))

    def test_out_of_range_latitude_rejected_by_model(self):
        shop = Shop(
            name="Invalid Lat",
            owner=self.owner,
            latitude=Decimal("90.000001"),
            longitude=Decimal("38.000000"),
        )
        with self.assertRaises(ValidationError) as ctx:
            shop.full_clean()
        self.assertIn("latitude", ctx.exception.message_dict)

        shop.latitude = Decimal("-90.000001")
        with self.assertRaises(ValidationError) as ctx:
            shop.full_clean()
        self.assertIn("latitude", ctx.exception.message_dict)

    def test_out_of_range_longitude_rejected_by_model(self):
        shop = Shop(
            name="Invalid Lng",
            owner=self.owner,
            latitude=Decimal("9.000000"),
            longitude=Decimal("180.000001"),
        )
        with self.assertRaises(ValidationError) as ctx:
            shop.full_clean()
        self.assertIn("longitude", ctx.exception.message_dict)

        shop.longitude = Decimal("-180.000001")
        with self.assertRaises(ValidationError) as ctx:
            shop.full_clean()
        self.assertIn("longitude", ctx.exception.message_dict)


class ShopDetailExposureTest(TestCase):
    """The shop detail endpoint is readable anonymously — internal fields on it
    are readable anonymously too unless the serializer withholds them."""

    def setUp(self):
        self.owner = User.objects.create_user(
            username="shop_owner", email="owner@example.com", password="pass"
        )
        self.other = User.objects.create_user(
            username="rival", email="rival@example.com", password="pass"
        )
        self.shop = Shop.objects.create(
            name="Bole Electronics",
            owner=self.owner,
            phone="+251911100001",
            telegram_chat_id="987654321",
            latitude=Decimal("9.024970"),
            longitude=Decimal("38.746890"),
        )
        self.shop_no_coords = Shop.objects.create(
            name="Merkato Accessories",
            owner=self.owner,
            phone="+251911100002",
        )
        self.url = f"/api/v1/shops/{self.shop.slug}/"
        self.url_no_coords = f"/api/v1/shops/{self.shop_no_coords.slug}/"

    def test_anonymous_detail_hides_internal_fields(self):
        response = APIClient().get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data)
        self.assertNotIn("owner", response.data)
        self.assertEqual(response.data["phone"], "+251911100001")

    def test_another_merchant_cannot_read_the_chat_id(self):
        client = APIClient()
        client.force_authenticate(self.other)

        response = client.get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data)

    def test_owner_still_sees_their_own_chat_id(self):
        client = APIClient()
        client.force_authenticate(self.owner)

        response = client.get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["telegram_chat_id"], "987654321")

    def test_list_never_carried_the_chat_id(self):
        response = APIClient().get("/api/v1/shops/")

        self.assertEqual(response.status_code, 200)
        self.assertNotIn("telegram_chat_id", response.data["results"][0])

    def test_anonymous_detail_exposes_coordinates(self):
        response = APIClient().get(self.url)

        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.data["latitude"], "9.024970")
        self.assertEqual(response.data["longitude"], "38.746890")

    def test_anonymous_detail_returns_null_coordinates_when_unset(self):
        response = APIClient().get(self.url_no_coords)

        self.assertEqual(response.status_code, 200)
        self.assertIsNone(response.data["latitude"])
        self.assertIsNone(response.data["longitude"])

    def test_list_exposes_coordinates(self):
        response = APIClient().get("/api/v1/shops/")

        self.assertEqual(response.status_code, 200)
        by_slug = {s["slug"]: s for s in response.data["results"]}
        self.assertEqual(by_slug[self.shop.slug]["latitude"], "9.024970")
        self.assertEqual(by_slug[self.shop.slug]["longitude"], "38.746890")
        self.assertIsNone(by_slug[self.shop_no_coords.slug]["latitude"])
        self.assertIsNone(by_slug[self.shop_no_coords.slug]["longitude"])


